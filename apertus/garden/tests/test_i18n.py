from __future__ import annotations

import json
import re
import runpy
import unittest
from pathlib import Path


GARDEN_DIR = Path(__file__).resolve().parents[1]
STATIC_DIR = GARDEN_DIR / "static"


class EnglishInterfaceContractTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.runtime = (STATIC_DIR / "i18n.js").read_text(encoding="utf-8")
        source = (STATIC_DIR / "i18n-catalog.generated.js").read_text(
            encoding="utf-8"
        )
        prefix = "window.ProbabilityGardenEnglishCatalogue = "
        if not source.startswith("// Generated by"):
            raise AssertionError("Generated catalogue is missing its provenance header")
        payload = source[source.index(prefix) + len(prefix) :].strip()
        cls.catalogue = json.loads(payload.removesuffix(";"))

    def test_catalogue_covers_every_workbench_area(self) -> None:
        self.assertEqual(
            set(self.catalogue),
            {
                "model-comparison",
                "model-admin",
                "model-comparison-runtime",
                "comparison-api",
                "detector-readers-api",
                "backends",
                "archive",
                "attribution",
                "common",
                "contrast",
                "detector",
                "embeddings",
                "garden",
                "guide",
                "jlens",
                "patching",
                "raw",
                "server",
                "shell",
                "steering",
                "surprise",
                "tokenization",
                "tuned",
            },
        )
        for page, translations in self.catalogue.items():
            with self.subTest(page=page):
                self.assertTrue(translations)
                self.assertTrue(all(translations.values()))
                for source, translated in translations.items():
                    self.assertEqual(
                        sorted(re.findall(r"__PG_SLOT_\d+__", source)),
                        sorted(re.findall(r"__PG_SLOT_\d+__", translated)),
                        f"Placeholder mismatch in {page}: {source!r}",
                    )

    def test_every_extracted_czech_interface_string_has_a_translation(self) -> None:
        """Keep later UI work from silently reopening Czech-only islands."""
        builder = runpy.run_path(
            str(GARDEN_DIR / "scripts" / "build-i18n-catalog.py")
        )
        extracted = builder["collect"]()
        for page, sources in extracted.items():
            with self.subTest(page=page):
                missing = sorted(set(sources) - set(self.catalogue.get(page, {})))
                self.assertEqual(
                    missing,
                    [],
                    f"Untranslated interface strings in {page}: {missing[:5]!r}",
                )

    def test_runtime_translates_dynamic_content_without_a_network_service(self) -> None:
        self.assertIn("MutationObserver", self.runtime)
        self.assertIn("translatePristineControl", self.runtime)
        self.assertIn("script, style, code, pre, textarea", self.runtime)
        self.assertIn("window.ProbabilityGardenEnglishCatalogue", self.runtime)
        self.assertNotIn("fetch(", self.runtime)
        self.assertIn('localeTag: () => language === "en"', self.runtime)
        for protected_content in (
            ".prediction-token",
            ".trajectory-completion",
            ".heatmap-token",
            ".experiment-prompt",
            ".observed-token",
        ):
            self.assertIn(protected_content, self.runtime)

    def test_key_methodological_terms_have_curated_translations(self) -> None:
        expected = {
            "Rozcestí": "Forking Paths",
            "Rozcestí – domů": "Forking Paths — home",
            "Výzkum a výuka": "Research and teaching",
            "Pravděpodobnostní zahrada": "Probability Garden",
            "Překvapení textu": "Text surprisal",
            "Kontrast kontextů": "Context contrast",
            "Kauzální přenos": "Causal transfer",
            "Průvodce workbenchem": "Workbench guide",
            "Čtečka": "Readout",
            "Reziduální proud": "Residual stream",
            "L__PG_SLOT_0__ · rozchod": "L__PG_SLOT_0__ · divergence",
            "__PG_SLOT_0__ ID ve forwardu": "__PG_SLOT_0__ IDs in the forward pass",
            "nepozorován": "not observed",
            "Žádný pokles JS pod polovinu kořene nepřetrval do konce pozorovaného úseku.": "No drop in JS below half the root persisted to the end of the observed segment.",
        }
        for source, target in expected.items():
            with self.subTest(source=source):
                self.assertIn(f'"{source}": "{target}"', self.runtime)


if __name__ == "__main__":
    unittest.main()
